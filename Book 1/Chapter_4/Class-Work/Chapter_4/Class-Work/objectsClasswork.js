// 1. Defining an Object
const dog = {
    name: 'Buddy',
    age: 3,
    color: 'Brown'
};

// Dot notation – add a new property
dog.breed = 'Labrador';
console.log("Breed:", dog.breed);

// Update the value of 'age'
dog.age = 4;
console.log("Dog Age:", dog.age);

// Log the full object
console.log("Dog Object:", dog);
