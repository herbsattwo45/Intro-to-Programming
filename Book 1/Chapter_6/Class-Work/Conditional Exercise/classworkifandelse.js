// Food availability (true = available, false = not available)
var pizza = false;
var burger = true;
var salad = false;

// Check food one by one
if (pizza) {
    console.log("I will eat pizza");
} else if (burger) {
    console.log("I will eat a burger");
} else if (salad) {
    console.log("I will eat salad");
} else {
    console.log("I will eat nothing");
}