// Start with 100 balloons
var balloons = 100;

// *= means "multiply and put the answer back into the variable"
// This is the same as: balloons = balloons * 2
balloons *= 2;

// 100 × 2 = 200
// Result:
balloons; // 200



// Start again with 100 balloons
var balloons = 100;

// /= means "divide and put the answer back into the variable"
// This is the same as: balloons = balloons / 4
balloons /= 4;

// 100 ÷ 4 = 25
// Result:
balloons; // 25
